function response({generation='g',offset=0,limit=200,total=1,query='',category='all',property_key}={}) {
  const items=Array.from({length:Math.max(0,Math.min(limit,total-offset))},(_,index)=>({type:'string',value:`v${offset+index}`,id:`string:"v${offset+index}"`,label:`"v${offset+index}"`,count:1}));
  const page={values:items,total,offset,limit,hasMore:offset+items.length<total};
  return {version:2,generation,totalDocuments:total,propertyKeys:['mixed','farAway'],catalog:{kind:category==='all'&&!query&&!property_key?'canonical':'query'},facets:{kinds:{values:[{value:'note',count:total}],hasMore:false},folders:{values:[],hasMore:false},tags:{values:[],hasMore:false},properties:{[property_key||'mixed']:page}}};
}
