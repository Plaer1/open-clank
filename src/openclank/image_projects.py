"""Managed Imps image projects — versioned editable state with Lore recovery.

Imps (the Image Processing Suite) keeps its editable layers, masks and text in a
managed project record that is bound to a stable Files image resource identity.
This module owns that record: creation, versioned state updates, the recoverable
Save operation, Save-a-copy, and the explicit portable project export.

Recovery uses the scoped shared History adapter; legacy local cache hooks are
not recovery authority. A Save captures a durable preimage before any mutation, then commits
expected revisions. Restore replays a captured preimage.

What the preimage actually contains (this is the honest limit):

* always — the original project state document and the original image revision;
* when the caller supplies ``image_bytes`` (an ``image_reader`` read of the
  writable original) — those exact bytes, base64-encoded with a sha256 digest.

When no image reader is available the payload records
``image_bytes_captured: false`` rather than pretending bytes were stored.

Nothing here deletes shared generated bytes, editor drafts, or the application
database. The record is additive storage for editable work.
"""

