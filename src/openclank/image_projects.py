    def export_project(
        self,
        *,
        project_id: str,
        owner: str,
        assets: Sequence[Mapping[str, Any]] = (),
    ) -> dict[str, Any]:
        """Explicit portable export of an editable project.

        The export carries the editable manifest plus the assets required to
        restore layers/text/masks. It is never written as a companion sidecar
        beside the image — callers decide where the bytes go.
        """
        record = self.get_project(project_id=project_id, owner=owner)
        return complete_portable_export({
            "kind": EXPORT_KIND,
            "schema_version": EXPORT_SCHEMA_VERSION,
            "name": record.name,
            "width": record.width,
            "height": record.height,
            "image": {
                **record.image_identity.as_key(),
                "revision": record.expected_image_revision,
            },
            "project_revision": record.project_revision,
            "state": dict(record.state),
            "assets": [dict(asset) for asset in assets],
        })

    def import_project(
        self,
        *,
        owner: str,
        image_identity: ImageResourceIdentity,
        bundle: Mapping[str, Any],
        expected_image_revision: str = "",
    ) -> ManagedProjectRecord:
        """Restore an exported project under a (possibly new) image resource.

        Unknown future keys in the bundle round-trip in the state document so a
        newer export can be held by an older reader without losing data.
        """
        if str(bundle.get("kind") or "") != EXPORT_KIND:
            raise ImageProjectError(
                "bundle is not an Imps project export", code="invalid_export"
            )
        validate_portable_import(bundle)
        state = _load_state(bundle.get("state"))
        # Preserve unknown top-level state keys verbatim.
        if isinstance(bundle.get("state"), Mapping):
            state = {**dict(bundle["state"]), **state}
        return self.create_project(
            owner=owner,
            image_identity=image_identity,
            name=str(bundle.get("name") or "Untitled"),
            width=bundle.get("width"),
            height=bundle.get("height"),
            state=state,
            expected_image_revision=expected_image_revision
            or str((bundle.get("image") or {}).get("revision") or ""),
        )
